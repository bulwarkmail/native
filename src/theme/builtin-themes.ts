// ThemePalette that the CSS defines; everything else keeps the base palette.
// Regenerate rather than hand-edit when the webmail themes change.
//
// Mapping (webmail --color-* -> ThemePalette): primary -> primary,
// primaryDark, textLink, navActive; ring -> primaryLight, borderFocus;
// accent -> primaryBg, primaryBgHover, surfaceHover; secondary -> surface;
// muted -> surfaceActive; foreground -> text; background -> textInverse;
// muted-foreground -> textSecondary, textMuted, read, navInactive;
// destructive -> error, navBadge; border -> borderLight; the rest by name.
// Translucent values of the solid-fill tokens (surfaces, cards, accent,
// popover) are composited onto the theme background, because RN has no
// backdrop blur and would show whatever lies underneath (Aurora Glass dark).
//
// Only the colour tokens are ported. The webmail's theme skins (fonts,
// radii, Elastic's dark task rail, Aurora's gradient mesh and frosted panes)
// and the "Flat fields" design-system theme have no native counterpart.
